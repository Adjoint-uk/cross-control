//! `service unit | install | uninstall`: start the daemon at login, using
//! this binary's own path so the definition is always correct for wherever
//! it was installed.
//!
//! - Linux: a systemd *user* service.
//! - Windows: a Task Scheduler task that runs at logon, as the user, in
//!   their desktop session. (A Windows *service* runs in session 0, away
//!   from the desktop, where it could neither capture nor inject input.)
//!   The task starts `cross-controlw`, which runs the daemon without a
//!   console window and restarts it if it fails.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use cross_control_daemon::setup;
use serde_json::json;

use crate::exit;
use crate::{Ctx, ServiceAction};

const UNIT_NAME: &str = "cross-control.service";
const TASK_NAME: &str = "cross-control";

pub async fn run(ctx: &Ctx, action: ServiceAction) -> anyhow::Result<u8> {
    let exe = std::env::current_exe()?;
    // Absolute, so the unit works whatever directory systemd starts it in.
    let config = ctx
        .config_path
        .as_ref()
        .map(|p| std::fs::canonicalize(p).unwrap_or_else(|_| p.clone()));
    // Carry a directory override into the service, or it would run with a
    // different identity and trust store than the one just configured.
    let env: Vec<(&str, String)> = [setup::CONFIG_DIR_ENV, setup::RUNTIME_DIR_ENV]
        .into_iter()
        .filter_map(|var| {
            let value = std::env::var(var).ok().filter(|v| !v.is_empty())?;
            Some((var, value))
        })
        .collect();
    if cfg!(windows) {
        return windows_task(ctx, action, &exe, config.as_deref(), &env).await;
    }
    let unit = unit_text(&exe, config.as_deref(), &env);
    match action {
        ServiceAction::Unit => {
            if ctx.json {
                Ctx::print_json(&json!({ "name": UNIT_NAME, "unit": unit }));
            } else {
                print!("{unit}");
            }
            Ok(exit::OK)
        }
        ServiceAction::Install { enable } => install(ctx, &unit, enable),
        ServiceAction::Uninstall => uninstall(ctx),
    }
}

/// Where systemd looks for this user's units.
fn unit_path() -> PathBuf {
    let config_root = setup::config_dir()
        .parent()
        .map_or_else(|| PathBuf::from("."), Path::to_path_buf);
    config_root.join("systemd/user").join(UNIT_NAME)
}

/// The systemd user unit that runs `exe start` (with `--config` if given).
pub fn unit_text(exe: &Path, config: Option<&Path>, env: &[(&str, String)]) -> String {
    let mut exec = format!("{} start", systemd_quote(&exe.to_string_lossy()));
    if let Some(config) = config {
        exec.push_str(" --config ");
        exec.push_str(&systemd_quote(&config.to_string_lossy()));
    }
    let mut extra_env = String::new();
    for (var, value) in env {
        let _ = writeln!(
            extra_env,
            "Environment={}",
            systemd_quote(&format!("{var}={value}"))
        );
    }
    format!(
        "\
# Generated by `cross-control service install`; regenerate rather than edit
# (or add overrides with `systemctl --user edit cross-control`).
#
# Input capture/emulation needs your user in the `input` group and
# read/write access to /dev/uinput.

[Unit]
Description=cross-control virtual KVM daemon
Documentation=https://github.com/Adjoint-uk/cross-control

[Service]
Type=simple
ExecStart={exec}
Restart=on-failure
RestartSec=5
Environment=RUST_LOG=info
{extra_env}
[Install]
WantedBy=default.target
"
    )
}

/// Quote one `ExecStart=` argument: double quotes, with backslashes and
/// quotes escaped and `%` doubled (systemd specifier syntax).
fn systemd_quote(arg: &str) -> String {
    let escaped = arg
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('%', "%%");
    format!("\"{escaped}\"")
}

fn systemctl(args: &[&str]) -> anyhow::Result<()> {
    let status = std::process::Command::new("systemctl")
        .arg("--user")
        .args(args)
        .status()
        .map_err(|e| anyhow::anyhow!("cannot run systemctl: {e}"))?;
    if !status.success() {
        anyhow::bail!("`systemctl --user {}` failed ({status})", args.join(" "));
    }
    Ok(())
}

fn install(ctx: &Ctx, unit: &str, enable: bool) -> anyhow::Result<u8> {
    ensure_linux()?;
    let path = unit_path();
    let changed = std::fs::read_to_string(&path).ok().as_deref() != Some(unit);
    if changed {
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir)?;
        }
        std::fs::write(&path, unit)?;
        systemctl(&["daemon-reload"])?;
    }
    if enable {
        systemctl(&["enable", "--now", UNIT_NAME])?;
    }
    if ctx.json {
        Ctx::print_json(&json!({ "changed": changed, "path": path, "enabled": enable }));
    } else if changed {
        println!("Installed {}.", path.display());
        if !enable {
            println!("Start it with: systemctl --user enable --now {UNIT_NAME}");
        }
    } else {
        println!("{} is up to date.", path.display());
    }
    Ok(exit::OK)
}

fn uninstall(ctx: &Ctx) -> anyhow::Result<u8> {
    ensure_linux()?;
    let path = unit_path();
    let changed = path.exists();
    if changed {
        // Best effort: the unit may already be stopped or disabled.
        let _ = systemctl(&["disable", "--now", UNIT_NAME]);
        std::fs::remove_file(&path)?;
        systemctl(&["daemon-reload"])?;
    }
    if ctx.json {
        Ctx::print_json(&json!({ "changed": changed, "path": path }));
    } else if changed {
        println!("Removed {}.", path.display());
    } else {
        println!("{} is not installed.", path.display());
    }
    Ok(exit::OK)
}

fn ensure_linux() -> anyhow::Result<()> {
    if cfg!(target_os = "linux") {
        Ok(())
    } else {
        anyhow::bail!("service management is implemented for Linux (systemd) and Windows only")
    }
}

/// `service` on Windows: the logon task.
async fn windows_task(
    ctx: &Ctx,
    action: ServiceAction,
    exe: &Path,
    config: Option<&Path>,
    env: &[(&str, String)],
) -> anyhow::Result<u8> {
    let launcher = exe.with_file_name(format!("cross-controlw{}", std::env::consts::EXE_SUFFIX));
    let user = match (std::env::var("USERDOMAIN"), std::env::var("USERNAME")) {
        (Ok(domain), Ok(name)) if !domain.is_empty() => format!("{domain}\\{name}"),
        (_, Ok(name)) => name,
        _ => anyhow::bail!("cannot tell the current user (USERNAME is not set)"),
    };
    let xml = task_xml(&launcher, config, env, &user);
    let path = setup::config_dir().join("cross-control-task.xml");

    match action {
        ServiceAction::Unit => {
            if ctx.json {
                Ctx::print_json(&json!({ "name": TASK_NAME, "task": xml }));
            } else {
                print!("{xml}");
            }
            Ok(exit::OK)
        }
        ServiceAction::Install { enable } => {
            if !launcher.exists() {
                anyhow::bail!(
                    "{} not found: install it next to {}",
                    launcher.display(),
                    exe.display()
                );
            }
            let bytes = utf16_with_bom(&xml);
            let registered = schtasks(&["/Query", "/TN", TASK_NAME]).is_ok();
            let changed = !registered || std::fs::read(&path).ok().as_deref() != Some(&bytes[..]);
            if changed {
                setup::write_private_file(&path, &bytes)?;
                let file = path.to_string_lossy();
                schtasks(&["/Create", "/TN", TASK_NAME, "/XML", &file, "/F"])?;
            }
            if enable {
                schtasks(&["/Run", "/TN", TASK_NAME])?;
            }
            if ctx.json {
                Ctx::print_json(&json!({
                    "changed": changed, "task": TASK_NAME, "path": path, "enabled": enable
                }));
            } else if changed {
                println!("Registered the logon task \"{TASK_NAME}\".");
                if !enable {
                    println!("It starts at your next logon; to start it now: schtasks /Run /TN {TASK_NAME}");
                }
            } else {
                println!("The logon task \"{TASK_NAME}\" is up to date.");
            }
            Ok(exit::OK)
        }
        ServiceAction::Uninstall => {
            let registered = schtasks(&["/Query", "/TN", TASK_NAME]).is_ok();
            // Stop the daemon cleanly first; `cross-controlw` then exits too.
            let endpoint = cross_control_daemon::control::Endpoint::current();
            let request = cross_control_daemon::control::Request::Stop;
            let _ = cross_control_daemon::control::request(&endpoint, request).await;
            if registered {
                let _ = schtasks(&["/End", "/TN", TASK_NAME]);
                schtasks(&["/Delete", "/TN", TASK_NAME, "/F"])?;
            }
            let _ = std::fs::remove_file(&path);
            if ctx.json {
                Ctx::print_json(&json!({ "changed": registered, "task": TASK_NAME }));
            } else if registered {
                println!("Removed the logon task \"{TASK_NAME}\".");
            } else {
                println!("The logon task \"{TASK_NAME}\" is not installed.");
            }
            Ok(exit::OK)
        }
    }
}

fn schtasks(args: &[&str]) -> anyhow::Result<()> {
    let output = std::process::Command::new("schtasks")
        .args(args)
        .output()
        .map_err(|e| anyhow::anyhow!("cannot run schtasks: {e}"))?;
    if !output.status.success() {
        anyhow::bail!(
            "`schtasks {}` failed: {}",
            args.join(" "),
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    Ok(())
}

/// The Task Scheduler definition: at `user`'s logon, run the launcher in
/// their session, with no time limit and no idle/battery conditions.
pub fn task_xml(
    launcher: &Path,
    config: Option<&Path>,
    env: &[(&str, String)],
    user: &str,
) -> String {
    let mut args: Vec<String> = Vec::new();
    for (var, value) in env {
        args.push("--env".to_string());
        args.push(windows_quote(&format!("{var}={value}")));
    }
    if let Some(config) = config {
        args.push("--config".to_string());
        args.push(windows_quote(&config.to_string_lossy()));
    }
    let user = xml_escape(user);
    let command = xml_escape(&launcher.to_string_lossy());
    let arguments = xml_escape(&args.join(" "));
    format!(
        r#"<?xml version="1.0" encoding="UTF-16"?>
<!-- Generated by `cross-control service install`; regenerate rather than edit. -->
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>cross-control virtual KVM daemon</Description>
    <URI>\{TASK_NAME}</URI>
  </RegistrationInfo>
  <Triggers>
    <LogonTrigger>
      <Enabled>true</Enabled>
      <UserId>{user}</UserId>
    </LogonTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <UserId>{user}</UserId>
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>false</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <IdleSettings>
      <StopOnIdleEnd>false</StopOnIdleEnd>
      <RestartOnIdle>false</RestartOnIdle>
    </IdleSettings>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>false</Hidden>
    <RunOnlyIfIdle>false</RunOnlyIfIdle>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <Priority>7</Priority>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>{command}</Command>
      <Arguments>{arguments}</Arguments>
    </Exec>
  </Actions>
</Task>
"#
    )
}

fn xml_escape(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

/// Quote one argument the way Windows programs split their command line
/// (`CommandLineToArgvW`): quotes only when needed, with backslashes
/// doubled before a quote.
pub fn windows_quote(arg: &str) -> String {
    if !arg.is_empty() && !arg.contains([' ', '\t', '"']) {
        return arg.to_string();
    }
    let mut out = String::from("\"");
    let mut backslashes = 0;
    for c in arg.chars() {
        match c {
            '\\' => backslashes += 1,
            '"' => {
                out.push_str(&"\\".repeat(backslashes * 2 + 1));
                out.push('"');
                backslashes = 0;
            }
            _ => {
                out.push_str(&"\\".repeat(backslashes));
                out.push(c);
                backslashes = 0;
            }
        }
    }
    out.push_str(&"\\".repeat(backslashes * 2));
    out.push('"');
    out
}

/// Task Scheduler reads task files as UTF-16.
fn utf16_with_bom(text: &str) -> Vec<u8> {
    let mut bytes = vec![0xFF, 0xFE];
    for unit in text.encode_utf16() {
        bytes.extend_from_slice(&unit.to_le_bytes());
    }
    bytes
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unit_runs_this_binary_with_quoted_args() {
        let unit = unit_text(
            Path::new("/opt/cross control/bin/cross-control"),
            Some(Path::new("/etc/cross-control/100%.toml")),
            &[("CROSS_CONTROL_CONFIG_DIR", "/srv/cc dir".to_string())],
        );
        assert!(unit.contains(
            "ExecStart=\"/opt/cross control/bin/cross-control\" start \
             --config \"/etc/cross-control/100%%.toml\""
        ));
        assert!(unit.contains("WantedBy=default.target"));
        assert!(unit.contains("Environment=\"CROSS_CONTROL_CONFIG_DIR=/srv/cc dir\"\n"));
    }

    #[test]
    fn windows_arguments_are_quoted_for_commandlinetoargvw() {
        assert_eq!(windows_quote("plain"), "plain");
        assert_eq!(windows_quote(""), "\"\"");
        assert_eq!(
            windows_quote(r"C:\cc dir\config.toml"),
            r#""C:\cc dir\config.toml""#
        );
        assert_eq!(windows_quote(r"C:\cc dir\"), r#""C:\cc dir\\""#);
        assert_eq!(windows_quote(r#"say "hi""#), r#""say \"hi\"""#);
    }

    #[test]
    fn task_runs_the_launcher_at_logon_in_the_users_session() {
        let xml = task_xml(
            Path::new(r"C:\Program Files\cross-control\cross-controlw.exe"),
            Some(Path::new(r"C:\Users\a&b\config.toml")),
            &[("CROSS_CONTROL_CONFIG_DIR", r"D:\cc dir".to_string())],
            r"PC\alice",
        );
        assert!(
            xml.contains("<Command>C:\\Program Files\\cross-control\\cross-controlw.exe</Command>")
        );
        assert!(xml.contains(
            "<Arguments>--env &quot;CROSS_CONTROL_CONFIG_DIR=D:\\cc dir&quot; \
             --config C:\\Users\\a&amp;b\\config.toml</Arguments>"
        ));
        assert!(xml.contains("<LogonType>InteractiveToken</LogonType>"));
        assert!(xml.contains("<UserId>PC\\alice</UserId>"));
        assert!(xml.contains("<ExecutionTimeLimit>PT0S</ExecutionTimeLimit>"));
    }

    #[test]
    fn task_file_is_utf16_with_a_bom() {
        assert_eq!(
            utf16_with_bom("<a/>"),
            [0xFF, 0xFE, b'<', 0, b'a', 0, b'/', 0, b'>', 0]
        );
    }

    #[test]
    fn unit_without_config_has_no_config_flag() {
        let unit = unit_text(Path::new("/usr/bin/cross-control"), None, &[]);
        assert!(unit.contains("ExecStart=\"/usr/bin/cross-control\" start\n"));
    }
}
